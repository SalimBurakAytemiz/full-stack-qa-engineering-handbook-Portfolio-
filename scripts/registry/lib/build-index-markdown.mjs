// Shared generation logic for the registry index, used by both
// build-indexes.mjs (the CLI that writes the file) and
// validate-registry.mjs (the generated-output-drift check, which
// regenerates this in memory and diffs it against the committed file —
// see Section 41's "generated-output drift" requirement).
// TR: Bu mantık İKİ çağıran arasında PAYLAŞILIR — CLI ve validator FARKLI
// kopyalar kullansaydı, biri güncellenip diğeri unutulabilirdi ve
// drift kontrolü kendi kendine sessizce yanlış geçerdi (P3-01: her alan
// adı değişikliği burada TEK bir yerde yapılır — bkz. `maturity` alanı
// yeniden adlandırmasının P2-01'de bu dosyada nasıl düzeltildiği).
import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

function loadYaml(root, relPath) {
  const full = path.join(root, relPath);
  if (!existsSync(full)) return null;
  return yaml.load(readFileSync(full, 'utf8'));
}

export function buildIndexMarkdown(root) {
  const competencyState = loadYaml(root, '01-SALIM-BURAK-DIGITAL-TWIN/registry/competency-state.yaml');
  const domainsCatalog = loadYaml(root, 'shared/registry/catalog/domains.yaml');
  const labsCatalog = loadYaml(root, 'shared/registry/catalog/labs.yaml');
  const patternsCatalog = loadYaml(root, 'shared/registry/catalog/patterns.yaml');
  const evidence = loadYaml(root, '06-EVIDENCE/evidence.yaml');
  const relationships = loadYaml(root, 'shared/registry/relationships/relationships.yaml');

  const lines = [];
  lines.push('<!-- GENERATED by scripts/registry/build-indexes.mjs — do not hand-edit. -->');
  lines.push('# Registry-Generated Index');
  lines.push('');
  lines.push(`Generated from ${['competency-state.yaml', 'domains.yaml', 'labs.yaml', 'patterns.yaml', 'evidence.yaml', 'relationships.yaml'].join(', ')} at build time.`);
  lines.push('');

  lines.push('## Competency Matrix (knowledge / professional / repository)');
  lines.push('');
  lines.push('| Competency | Knowledge | Professional | Repository |');
  lines.push('|---|---|---|---|');
  for (const c of competencyState.competencies) {
    const prof = c.professional.status || Object.entries(c.professional).map(([k, v]) => `${k}:${v}`).join(', ');
    lines.push(`| ${c.label} | ${c.knowledge} | ${prof} | ${c.repository.status} |`);
  }
  lines.push('');

  // TR: Codex post-audit fix (P2-01) — domains.yaml artık `exposure`
  // (kişisel exposure sözlüğü) değil `maturity` (D0-D5, evrensel katalog
  // olgunluğu) alanı taşıyor; bu tablo o yeniden adlandırmaya göre
  // güncellenmedikçe her satır sessizce "undefined" yazardı (drift
  // kontrolü bunu YAKALAMAZ, çünkü hem committed hem taze regenerasyon
  // AYNI kırık mantığı kullanırdı — bu, bir generator hatasının neden
  // yalnızca "diff eşleşiyor mu" kontrolüyle DEĞİL, üretilen İÇERİĞİN
  // kendisi incelenerek yakalanabileceğinin somut bir örneğidir).
  lines.push('## Domain Maturity');
  lines.push('');
  lines.push('| Domain | Maturity | Note |');
  lines.push('|---|---|---|');
  for (const d of domainsCatalog.items) {
    lines.push(`| ${d.label} | ${d.maturity} | ${d.note || ''} |`);
  }
  lines.push('');

  lines.push('## Executable Labs');
  lines.push('');
  lines.push('| Lab | Maturity | Path |');
  lines.push('|---|---|---|');
  for (const l of labsCatalog.items) {
    lines.push(`| ${l.label} | ${l.maturity} | \`${l.path}\` |`);
  }
  lines.push('');

  lines.push('## System Patterns');
  lines.push('');
  lines.push('| Pattern | Status | Path |');
  lines.push('|---|---|---|');
  for (const p of patternsCatalog.items) {
    lines.push(`| ${p.label} | ${p.status} | \`${p.path}\` |`);
  }
  lines.push('');

  lines.push('## Evidence');
  lines.push('');
  lines.push('| Evidence | Maturity | Artifact |');
  lines.push('|---|---|---|');
  for (const e of evidence.items) {
    lines.push(`| ${e.label} | ${e.maturity} | \`${e.artifact}\` |`);
  }
  lines.push('');

  lines.push(`## Relationships (${relationships.relationships.length} edges)`);
  lines.push('');
  lines.push('| From | Predicate | To |');
  lines.push('|---|---|---|');
  for (const r of relationships.relationships) {
    lines.push(`| ${r.from} | ${r.predicate} | ${r.to} |`);
  }

  // Codex final-verification fix (F7): no trailing lines.push('') here —
  // `join('\n') + '\n'` already terminates the file with exactly one
  // newline after the last real content line. The previous version had
  // BOTH a trailing empty-string push AND the `+ '\n'`, producing two
  // newlines at EOF (a blank line at end of file) — exactly what
  // `git diff --check` flags as "new blank line at EOF". Every OTHER
  // `lines.push('')` in this file is a real, intentional blank line
  // SEPARATING two sections — this was the one and only spot where an
  // identical-looking call was actually a trailing-whitespace bug rather
  // than deliberate formatting.
  return lines.join('\n') + '\n';
}
